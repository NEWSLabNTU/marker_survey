// Marker sheets and identification, and the tabs: the page talks to marker_survey_web's JSON API.
// robot.js adds the survey, check and map screens when the page is served by the robot.
'use strict';

const $ = (id) => document.getElementById(id);
let siteMap = '';          // text of a chosen marker_map.yaml
let timer = null;
let lastOk = false;

async function post(path, body) {
  const r = await fetch(path, {method: 'POST', headers: {'Content-Type': 'application/json'},
                               body: JSON.stringify(body)});
  return r;
}

function radio(name) {
  return document.querySelector(`input[name="${name}"]:checked`).value;
}

function job() {
  const unit = $('size_unit').value;
  const exact = radio('paper_mode') === 'exact';
  const border = $('border').value.trim();
  const list = radio('id_mode') === 'list';
  return {
    size: $('size').value ? `${$('size').value}${unit}` : '',
    count: list ? '' : $('count').value,
    ids: list ? $('ids').value : '',
    dictionary: $('dictionary').value,
    paper: exact ? 'exact' : $('paper').value,
    border: border ? `${border}${unit}` : '',
    per_page: $('one_per_page').checked ? '1' : 'auto',
    split: radio('split') === '1',
    labels: $('labels').checked,
    back_labels: $('back_labels').checked,
    site_map: siteMap,
  };
}

function showTab() {
  const name = location.hash.slice(1);
  const tab = document.querySelector(`.tab[data-tab="${name}"]`);
  const t = tab && !tab.hidden ? tab : document.querySelector('.tab');
  document.querySelectorAll('.tab').forEach((x) => x.classList.toggle('active', x === t));
  document.querySelectorAll('.panel').forEach((p) => p.classList.toggle('active', p.id === t.dataset.tab));
  document.dispatchEvent(new CustomEvent('tabchange', {detail: t.dataset.tab}));
}

function el(tag, cls, text) {
  const e = document.createElement(tag);
  if (cls) e.className = cls;
  if (text !== undefined) e.textContent = text;
  return e;
}

function showPlan(res) {
  const checks = $('checks');
  const previews = $('previews');
  checks.replaceChildren();
  previews.replaceChildren();
  lastOk = !!res.ok;
  $('download').disabled = !res.ok;
  if (!res.ok) {
    checks.append(el('div', 'check bad', res.error));
    return;
  }
  const s = res.summary;
  const paper = s.paper === 'exact'
    ? `exact pages of ${s.sheet_mm} × ${s.sheet_mm} mm`
    : `${s.paper} paper (${s.paper_mm[0]} × ${s.paper_mm[1]} mm), ${s.per_page} per page`;
  checks.append(el('div', 'check ok', `${s.count} markers, ${s.dictionary}, black square ${s.size_label}`));
  checks.append(el('div', 'check ok', `${paper}; white border ${s.border_mm} mm`));
  checks.append(el('div', 'check ok', s.split
    ? `${s.count} PDF files and a contact sheet, in one zip`
    : `one PDF of ${s.pages} pages, the last one${s.pages - s.marker_pages > 1 ? 's' : ''} listing every ID`));
  if (s.count > 1) checks.append(el('div', 'check ok', `IDs at least ${s.min_distance_bits} bits apart`));
  for (const w of s.warnings) checks.append(el('div', 'check warn', w));
  checks.append(el('div', 'ids', 'IDs: ' + s.ids.join(', ')));
  for (const p of res.previews) {
    const box = el('div', 'page');
    box.innerHTML = p.svg;               // generated by the server from the same layout as the PDF
    box.append(el('div', '', p.label));
    previews.append(box);
  }
  if (s.more_pages > 0) previews.append(el('div', 'more', `and ${s.more_pages} more pages`));
  const unit = $('size_unit').value;
  const per = {mm: 1, cm: 10, in: 25.4}[unit];
  const cell = +(s.cell_mm / per).toFixed(2);
  $('border').placeholder = `${cell}`;
  $('border_note').textContent = `Empty: one cell of the marker (${cell} ${unit}), the least a camera needs.`;
  $('download').textContent = s.split ? 'Download ZIP' : 'Download PDF';
}

async function update() {
  try {
    const r = await post('/api/sheets/plan', job());
    showPlan(await r.json());
  } catch (e) {
    showPlan({ok: false, error: 'the server does not answer: is marker_survey_web running?'});
  }
}

function later() {
  clearTimeout(timer);
  timer = setTimeout(update, 250);
}

async function download(format) {
  const body = job();
  body.format = format;
  const r = await post('/api/sheets/download', body);
  const type = r.headers.get('Content-Type') || '';
  if (type.startsWith('application/json')) {
    showPlan(await r.json());
    return;
  }
  const disp = r.headers.get('Content-Disposition') || '';
  const m = disp.match(/filename="([^"]+)"/);
  const blob = await r.blob();
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = m ? m[1] : 'markers';
  document.body.append(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(a.href), 10000);
}

async function init() {
  const info = await (await fetch('/api/info')).json();
  for (const d of info.dictionaries) {
    const o = el('option', '', d);
    o.value = d;
    if (d === info.default_dictionary) o.selected = true;
    $('dictionary').append(o);
    const o2 = el('option', '', d);
    o2.value = d;
    $('id_dictionary').append(o2);
  }
  for (const p of info.papers) {
    const o = el('option', '', p);
    o.value = p;
    $('paper').append(o);
  }

  // tabs follow the address (#survey, #check, ...), so a link or an iframe can open one
  document.querySelectorAll('.tab').forEach((t) => t.addEventListener('click', () => {
    location.hash = t.dataset.tab;
  }));
  window.addEventListener('hashchange', showTab);
  showTab();

  $('job').addEventListener('input', later);
  $('job').addEventListener('change', later);
  $('size_unit').addEventListener('change', () => { $('border_unit').textContent = $('size_unit').value; });
  $('ids').addEventListener('focus', () => {
    document.querySelector('input[name="id_mode"][value="list"]').checked = true;
  });
  $('site').addEventListener('change', async () => {
    const f = $('site').files[0];
    siteMap = f ? await f.text() : '';
    $('site_note').textContent = f ? `IDs in ${f.name} are not used again.` : '';
    later();
  });
  $('download').addEventListener('click', (e) => { e.preventDefault(); if (lastOk) download(null); });
  $('download_csv').addEventListener('click', (e) => { e.preventDefault(); download('csv'); });

  $('size_help_toggle').addEventListener('click', (e) => {
    e.preventDefault();
    $('size_help').hidden = !$('size_help').hidden;
  });
  $('size_suggest').addEventListener('click', async () => {
    const r = await (await post('/api/size', {
      ceiling: $('h_ceiling').value, camera_height: $('h_camera').value, hfov: $('h_hfov').value,
      width: $('h_w').value, height: $('h_h').value})).json();
    if (!r.ok) { $('size_result').textContent = r.error; return; }
    $('size_unit').value = 'cm';
    $('border_unit').textContent = 'cm';
    $('size').value = r.size_cm;
    let text = `${r.size_cm} cm (${r.px_per_cell} pixels per cell). The camera sees a whole marker ` +
      `within ${r.zone_radius_m} m of it.`;
    if (r.route_spacing_m) text += ` Along routes, place one at least every ${r.route_spacing_m} m, ` +
      `and one at each stop.`;
    $('size_result').textContent = text;
    update();
  });

  $('photo').addEventListener('change', async () => {
    const f = $('photo').files[0];
    if (!f) return;
    $('id_result').textContent = 'Reading the photo...';
    $('id_image').removeAttribute('src');
    const url = await new Promise((ok) => { const fr = new FileReader(); fr.onload = () => ok(fr.result); fr.readAsDataURL(f); });
    const r = await (await post('/api/identify', {image: url, dictionary: $('id_dictionary').value})).json();
    if (!r.ok) { $('id_result').textContent = r.error; return; }
    $('id_result').textContent = r.ids.length
      ? `${r.dictionary}: ${r.ids.map((i) => 'ID ' + i).join(', ')}`
      : 'No marker found. Get closer, hold still, and keep the whole marker and its white border in the picture.';
    $('id_image').src = r.image;
    $('photo').value = '';
  });

  update();
}

init();
